const root=new URL('../../',import.meta.url)
const check=process.argv.includes('--check')
async function save(file, next) {
 const url=new URL(file,root), current=await readFile(url,'utf8').catch(()=>null)
 if(current===next)return
 if(check)throw Error(`Navigation is out of date: ${file}; run npm run sync:navigation`)
 await writeFile(url,next)
}
for(const [directory,slug] of [['evaltube','evaltube'],['eval-papers','evalpapers'],['ai-time-capsule','timecapsule'],['auto-eval','autoeval'],['policy-radar-cn','policy-radar']]) {
 const file=`sites/${directory}/public/index.html`
 let html=stripNavigation(await readFile(new URL(file,root),'utf8'))
 // Keep the link inside each app's toolbar, outside dynamically rendered content.
 html=html.replace('</header>',`<!-- portfolio-nav:start -->${navigation({slug})}<!-- portfolio-nav:end --></header>`)
 await save(file,html)
 const stylesheet=`sites/${directory}/public/styles.css`
 let styles=await readFile(new URL(stylesheet,root),'utf8')
 styles=styles.replace(/\n?\/\* portfolio-nav:start \*\/[\s\S]*?\/\* portfolio-nav:end \*\//g,'')
 await save(stylesheet,styles+`\n/* portfolio-nav:start */\n${css}\n${adaptations[directory]}\n/* portfolio-nav:end */`)
}
